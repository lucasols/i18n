import {
  type CompiledLocale,
  type CompiledPlural,
  type CompiledTranslation,
} from '@ls-stack/i18n-core';
import { createElement, Fragment, type ReactNode } from 'react';
import {
  assertDevScope,
  getDevFallback,
  getState,
  registerDevFallbacks,
  reportErrorOnce,
} from './state';
import type { JsxInterpolation } from './translate';

const PLACEHOLDER_SPLITTER = /{(\d+)}/;
const MISSING_TRANSLATION = '…';

/** Literal parts as strings and interpolation positions (0 based) as numbers */
type TemplateParts = (string | number)[];

let partsCache: (TemplateParts | undefined)[] = [];
let partsCacheLocale: CompiledLocale | null = null;

/**
 * Registers the source strings of translations, used by the code generated by
 * the vite plugin on the dev server so translations added after the locale was
 * loaded still render.
 */
export function __registerDevFallbacks(
  entries: [id: number, fallback: CompiledTranslation][],
): void {
  registerDevFallbacks(entries);
}

function getTranslation(id: number): CompiledTranslation | undefined {
  const { compiledTranslations, translations, activeLocale } = getState();

  if (!compiledTranslations) {
    if (!translations) return undefined;

    reportErrorOnce(
      'uncompiled-locale',
      `I18n error: the locale "${activeLocale}" was not compiled by the vite plugin, the locale loader must import a JSON file from the plugin localesDir`,
    );
    return getDevFallback(id);
  }

  return compiledTranslations[id] ?? getDevFallback(id);
}

function parseTemplate(template: string): TemplateParts {
  const parts: TemplateParts = [];
  const splitted = template.split(PLACEHOLDER_SPLITTER);

  for (let i = 0; i < splitted.length; i++) {
    const part = splitted[i];
    if (!part) continue;

    parts.push(i % 2 === 0 ? part : Number(part) - 1);
  }

  return parts;
}

/** Plural forms: 0 = zero, 1 = one, 2 = +2 (replaces `#`), 3 = many */
type PluralForm = 0 | 1 | 2 | 3;

const FORMS_PER_ID = 4;

/**
 * Parsed templates are cached by `id * 4 + plural form`, simple translations
 * use the form `0`.
 */
function getCachedTemplateParts(
  id: number,
  form: PluralForm,
  template: string,
): TemplateParts {
  const { compiledTranslations } = getState();

  if (partsCacheLocale !== compiledTranslations) {
    partsCacheLocale = compiledTranslations;
    partsCache = new Array<TemplateParts | undefined>(
      (compiledTranslations?.length ?? 0) * FORMS_PER_ID,
    );
  }

  const cacheKey = id * FORMS_PER_ID + form;
  let parts = partsCache[cacheKey];

  if (!parts) {
    parts = parseTemplate(template);
    partsCache[cacheKey] = parts;
  }

  return parts;
}

/** `count` replaces the first `#` of the template */
function interpolateParts(
  parts: TemplateParts,
  exprs: (string | number)[],
  count?: string,
): string {
  let result = '';
  let pendingCount = count;

  for (const part of parts) {
    if (typeof part !== 'string') {
      result += exprs[part] ?? '';
    } else if (pendingCount !== undefined && part.includes('#')) {
      result += part.replace('#', pendingCount);
      pendingCount = undefined;
    } else {
      result += part;
    }
  }

  return result;
}

function interpolatePartsJsx(
  parts: TemplateParts,
  exprs: JsxInterpolation[],
  count?: string,
): ReactNode {
  const children: ReactNode[] = [];
  let pendingCount = count;

  for (const part of parts) {
    if (typeof part !== 'string') {
      const expr = exprs[part];
      if (expr !== undefined) children.push(expr);
    } else if (pendingCount !== undefined && part.includes('#')) {
      children.push(part.replace('#', pendingCount));
      pendingCount = undefined;
    } else {
      children.push(part);
    }
  }

  return createElement(Fragment, null, ...children);
}

function selectPluralForm(num: number, plural: CompiledPlural): PluralForm {
  if (num === 0 && plural[0] !== 0) return 0;
  if (num === 1 && plural[1] !== 0) return 1;
  if (plural.length === 5 && num > plural[4]) return 3;
  return 2;
}

function getPluralTemplate(plural: CompiledPlural, form: PluralForm): string {
  if (form === 0 && plural[0] !== 0) return plural[0];
  if (form === 1 && plural[1] !== 0) return plural[1];
  if (form === 3 && plural.length === 5) return plural[3];
  return plural[2];
}

/** Compiled version of `__`, generated by the vite plugin */
export function __t(id: number, ...exprs: (string | number)[]): string {
  assertDevScope();
  const translation = getTranslation(id);

  if (typeof translation === 'string') {
    if (exprs.length === 0) return translation;

    return interpolateParts(getCachedTemplateParts(id, 0, translation), exprs);
  }

  return translation === 0 ? MISSING_TRANSLATION : '';
}

/** Compiled version of `__p`, generated by the vite plugin */
export function __tp(
  id: number,
  num: number,
  ...exprs: (string | number)[]
): string {
  assertDevScope();
  const translation = getTranslation(id);

  if (translation === undefined) return '';
  if (translation === 0) return MISSING_TRANSLATION;

  const form =
    typeof translation === 'string' ? 2 : selectPluralForm(num, translation);
  const template =
    typeof translation === 'string' ? translation : (
      getPluralTemplate(translation, form)
    );
  const count = form === 2 ? String(num) : undefined;

  if (exprs.length === 0) {
    return count === undefined ? template : template.replace('#', count);
  }

  return interpolateParts(
    getCachedTemplateParts(id, form, template),
    exprs,
    count,
  );
}

